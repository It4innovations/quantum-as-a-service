"""Generate tests/README.md: offline test results and code coverage of qheappe_client.

Runs the offline tests (``tests/qheappe``, ``-m "not integration"``) under coverage
and writes the results to ``tests/README.md``. Live tests are never run, so no
credentials or allocation are needed.

Usage (from the repository root, with ``qaas[iqm_qiskit,testenv]`` installed)::

    python scripts/update_test_readme.py
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "tests" / "README.md"
TEST_PATH = "tests/qheappe"
MARKER = "not integration"


def run(
    *args: str, env: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        args, check=False, cwd=ROOT, text=True, capture_output=True, env=env
    )


def run_tests(junit: Path, cov_json: Path) -> int:
    """Run the offline tests under coverage; returns pytest's exit code."""
    proc = run(
        sys.executable,
        "-m",
        "pytest",
        TEST_PATH,
        "-m",
        MARKER,
        "-q",
        "-p",
        "no:cacheprovider",
        "--cov",
        "--cov-report=",
        f"--cov-report=json:{cov_json}",
        f"--junitxml={junit}",
        # Keep the coverage data file out of the repository.
        env={**os.environ, "COVERAGE_FILE": str(junit.with_name(".coverage"))},
    )
    print(proc.stdout.strip().splitlines()[-1] if proc.stdout.strip() else "")
    if proc.returncode not in (0, 1):  # 1 = some tests failed; still report them
        sys.stderr.write(proc.stdout + proc.stderr)
        sys.exit(f"pytest failed with exit code {proc.returncode}")
    return proc.returncode


def test_results(junit: Path) -> tuple[Counter[str], dict[str, Counter[str]]]:
    """Outcome totals and per-file outcome counts from a JUnit XML report."""
    totals: Counter[str] = Counter()
    per_file: dict[str, Counter[str]] = {}
    for case in ET.parse(junit).getroot().iter("testcase"):
        if case.find("failure") is not None or case.find("error") is not None:
            outcome = "failed"
        elif (skipped := case.find("skipped")) is not None:
            outcome = "xfailed" if skipped.get("type") == "pytest.xfail" else "skipped"
        else:
            outcome = "passed"
        module = case.get("classname", "").split(".")
        name = next((m for m in module if m.startswith("test_")), module[0])
        per_file.setdefault(f"{name}.py", Counter())[outcome] += 1
        totals[outcome] += 1
    return totals, per_file


def coverage_table(cov_json: Path) -> tuple[str, str]:
    """Total percentage and a Markdown table of per-file coverage."""
    data = json.loads(cov_json.read_text())
    rows = [
        "| File | Statements | Missed | Branches | Partial | Coverage |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for path, info in sorted(data["files"].items()):
        s = info["summary"]
        if not s["num_statements"]:
            continue
        rel = path.split("qheappe_client/", 1)[-1]
        rows.append(
            f"| `{rel}` | {s['num_statements']} | {s['missing_lines']} "
            f"| {s.get('num_branches', 0)} | {s.get('num_partial_branches', 0)} "
            f"| {s['percent_covered_display']}% |"
        )
    t = data["totals"]
    rows.append(
        f"| **Total** | **{t['num_statements']}** | **{t['missing_lines']}** "
        f"| **{t.get('num_branches', 0)}** | **{t.get('num_partial_branches', 0)}** "
        f"| **{t['percent_covered_display']}%** |"
    )
    return t["percent_covered_display"], "\n".join(rows)


def library_version(name: str) -> str:
    from importlib import metadata

    try:
        return metadata.version(name)
    except metadata.PackageNotFoundError:
        return "not installed"


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        junit, cov_json = Path(tmp, "junit.xml"), Path(tmp, "coverage.json")
        exit_code = run_tests(junit, cov_json)
        totals, per_file = test_results(junit)
        total_cov, table = coverage_table(cov_json)

    commit = run("git", "rev-parse", "--short", "HEAD").stdout.strip() or "unknown"
    outcomes = ("passed", "failed", "xfailed", "skipped")
    summary = ", ".join(f"{totals[o]} {o}" for o in outcomes if totals[o])
    file_rows = "\n".join(
        f"| `{name}` | " + " | ".join(str(c[o]) for o in outcomes) + " |"
        for name, c in sorted(per_file.items())
    )

    README.write_text(
        f"""# Tests

<!-- Generated by scripts/update_test_readme.py. Do not edit by hand. -->

Offline test results and coverage of `qheappe_client`, generated by
[`scripts/update_test_readme.py`](../scripts/update_test_readme.py) at commit
`{commit}` (Python {sys.version.split()[0]}, qiskit {library_version("qiskit")},
iqm-client {library_version("iqm-client")}).

- **Tests:** {summary}{" (some tests FAILED)" if exit_code else ""}
- **Coverage:** {total_cov}% (statements and branches)

Only the offline suite is measured (`pytest {TEST_PATH} -m "{MARKER}"`). Live
tests (marker `integration`, needing LEXIS credentials) and the legacy
`tests/qaas` suite are not included.

Regenerate:

```bash
pip install -e ".[iqm_qiskit,testenv]"
python scripts/update_test_readme.py
```

## Test results by file

| File | Passed | Failed | Xfailed | Skipped |
| --- | ---: | ---: | ---: | ---: |
{file_rows}

## Coverage by module

{table}
"""
    )
    print(f"Wrote {README.relative_to(ROOT)}: {summary}; coverage {total_cov}%")


if __name__ == "__main__":
    main()
